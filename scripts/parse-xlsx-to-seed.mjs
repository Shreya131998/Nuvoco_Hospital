/**
 * Generates supabase/seed.sql from the workbooks in data/source/.
 * Only used by the Postgres backend — see scripts/init-sheet.mjs for Sheets.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { parseWorkbooks } from './parse-workbooks.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const q = (v) =>
  v === null || v === undefined || v === '' ? 'null' : `'${String(v).replace(/'/g, "''")}'`;

const { staff, boxes, items, points, medicines, ITEM_HI } = await parseWorkbooks();

const out = [];
const w = (s = '') => out.push(s);

// ---------------------------------------------------------------
// Emit seed.sql
// ---------------------------------------------------------------
w('-- GENERATED by scripts/parse-xlsx-to-seed.mjs — do not edit by hand.');
w('-- Source: data/source/*.xlsx');
w(`-- ${staff.length} staff · ${boxes.length} boxes · ${items.length} kit items · ${points.length} check points · ${medicines.length} medicines`);
w('');
w('begin;');
w('');
w('truncate staff, first_aid_box, first_aid_item, vehicle,');
w('         vehicle_check_point, medicine restart identity cascade;');
w('');

w('-- Staff (first aiders named on the first aid box register) ----');
w('insert into staff (name, mobile, role) values');
w(staff.map((s) => `  (${q(s.name)}, ${q(s.mobile)}, 'first_aider')`).join(',\n') + ';');
w('');

w('-- 41 first aid boxes ------------------------------------------');
w('insert into first_aid_box (box_no, location, first_aider_id) values');
w(
  boxes
    .map(
      (b) =>
        `  (${b.boxNo}, ${q(b.loc)}, ${
          b.aider ? `(select id from staff where name = ${q(b.aider)})` : 'null'
        })`
    )
    .join(',\n') + ';'
);
w('');

w('-- 17 standard kit items ---------------------------------------');
w('insert into first_aid_item (sr_no, name_en, name_hi, spec, standard_qty) values');
w(
  items
    .map(
      (i) =>
        `  (${i.sr}, ${q(i.name)}, ${q(ITEM_HI[i.name] || null)}, ${q(i.spec)}, ${i.qty})`
    )
    .join(',\n') + ';'
);
w('');

w('-- Vehicles. The source sheet leaves the registration blank, so this');
w('-- is a placeholder the admin renames on first use.');
w("insert into vehicle (vehicle_no, label) values ('CG-00-0000', 'Ambulance');");
w('');

w('-- 23 bilingual vehicle check points ---------------------------');
w('insert into vehicle_check_point (sort_order, label_hi, label_en) values');
w(points.map((p) => `  (${p.order}, ${q(p.hi)}, ${q(p.en)})`).join(',\n') + ';');
w('');

w('-- 99 medicines across 12 categories ---------------------------');
w('insert into medicine (sort_order, category, name) values');
w(medicines.map((m) => `  (${m.order}, ${q(m.category)}, ${q(m.name)})`).join(',\n') + ';');
w('');
w('commit;');
w('');

writeFileSync(join(ROOT, 'supabase', 'seed.sql'), out.join('\n'));

const cats = [...new Set(medicines.map((m) => m.category))];
console.log('seed.sql written');
console.log(`  staff        ${staff.length}`);
console.log(`  boxes        ${boxes.length}`);
console.log(`  kit items    ${items.length}`);
console.log(`  check points ${points.length}`);
console.log(`  medicines    ${medicines.length} in ${cats.length} categories`);
const multi = staff.filter((s) => s.variants > 1);
if (multi.length) {
  console.log('\n  NOTE — these names carry more than one mobile number in the');
  console.log('  source sheet; the most frequent was kept. Please verify:');
  multi.forEach((s) => console.log(`    ${s.name} -> kept ${s.mobile}`));
}
